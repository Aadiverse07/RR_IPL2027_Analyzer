"""Build Phase 2 innings-1 par and pressure components only.

Chase pressure is intentionally not implemented here; it requires an owner
decision for the three unresolved DLS/outcome exceptions before validation.
"""
from __future__ import annotations
import csv
import json
import math
from collections import defaultdict
from pathlib import Path
import yaml

ROOT=Path(__file__).resolve().parents[2]
BALLS=ROOT/'data/processed/balls_primary.csv'
CONFIG=ROOT/'config/methodology.yaml'
OUT=ROOT/'data/interim/balls_pressure_innings1.csv'
REPORT=ROOT/'reports/phase_2'

def read_rows(path):
    with path.open(encoding='utf-8-sig',newline='') as f:
        return list(csv.DictReader(f))

def write_rows(path, rows):
    path.parent.mkdir(parents=True,exist_ok=True)
    fields=list(rows[0]) if rows else []
    with path.open('w',encoding='utf-8',newline='') as f:
        w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(rows)

def build():
    cfg=yaml.safe_load(CONFIG.read_text(encoding='utf-8'))
    rows=[r for r in read_rows(BALLS) if int(r['innings'])==1]
    min_n=int(cfg['pressure']['innings1_par']['minimum_legal_balls'])
    half=int(cfg['pressure']['innings1_par']['smoothing_neighbour_half_window'])
    ddof=int(cfg['pressure']['innings1_par']['standard_deviation_ddof'])
    z_min=float(cfg['pressure']['innings1_batting']['behind_par_z_min'])
    collapse_min=int(cfg['pressure']['innings1_batting']['collapse_wickets_min'])
    win=int(cfg['pressure']['innings1_batting']['collapse_legal_ball_window'])
    # One cumulative score per match at each legal-ball count. Use only regular innings.
    scores=defaultdict(dict)
    for r in rows:
        n=int(r['legal_balls_before'])
        if n>0 and (n not in scores[r['match_id']]):
            scores[r['match_id']][n]=int(r['team_runs_before'])
        # At the first delivery after a legal ball count, team_runs_before is the
        # score after that many legal balls. The earliest row (n=0) is not par-eligible.
    match_formats={r['match_id']:r['format'] for r in rows}
    by_format_n=defaultdict(list)
    for mid,points in scores.items():
        fmt=match_formats[mid]
        for n,value in points.items():by_format_n[(fmt,n)].append((mid,value))
    out=[]
    for r in rows:
        n=int(r['legal_balls_before']);mid=r['match_id'];fmt=r['format']
        eligible=n>=min_n
        par=sd=zbehind=zahead=''
        if eligible:
            sample=[]
            for neighbour in range(max(1,n-half),n+half+1):
                sample.extend(value for other_mid,value in by_format_n[(fmt,neighbour)] if other_mid!=mid)
            if sample:
                par=sum(sample)/len(sample)
                variance=sum((x-par)**2 for x in sample)/(len(sample)-ddof) if len(sample)>ddof else 0.0
                sd=math.sqrt(variance)
                if sd>0:
                    actual=int(r['team_runs_before'])
                    zbehind=(par-actual)/sd
                    zahead=(actual-par)/sd
        # The Phase 2 specification's >=12 legal-ball eligibility applies to
        # both branches of the innings-1 batting union, including collapse.
        collapse=eligible and int(r['wickets_in_previous_12_legal_balls'])>=collapse_min
        behind=bool(eligible and zbehind!='' and zbehind>=z_min)
        ahead=bool(eligible and zahead!='' and zahead>=float(cfg['pressure']['innings1_bowling']['ahead_par_z_min']))
        batting=behind or collapse
        row=dict(r)
        row.update({'par_runs_loo':par,'par_sd_loo':sd,'z_behind_par':zbehind,'z_ahead_par':zahead,
            'par_eligible':str(bool(eligible and sd!='' and sd>0)).lower(),
            'press_bat_par':str(behind).lower(),'press_bat_collapse':str(collapse).lower(),
            'press_bat_union':str(batting).lower(),'press_bowl_ahead':str(ahead).lower()})
        out.append(row)
    write_rows(OUT,out)
    REPORT.mkdir(parents=True,exist_ok=True)
    summary={'rows':len(out),'matches':len({r['match_id'] for r in out}),
        'par_eligible_rows':sum(r['par_eligible']=='true' for r in out),
        'excluded_before_minimum_legal_balls':sum(int(r['legal_balls_before'])<min_n for r in out),
        'press_bat_par':sum(r['press_bat_par']=='true' for r in out),
        'press_bat_collapse':sum(r['press_bat_collapse']=='true' for r in out),
        'press_bat_union':sum(r['press_bat_union']=='true' for r in out),
        'press_bowl_ahead':sum(r['press_bowl_ahead']=='true' for r in out),
        'leave_one_match_out':True,'chase_pressure':'NOT GENERATED BY THIS FIRST-INNINGS-ONLY BUILD',
        'smoothing':'configured neighbourhood; operational assumption is n-1 through n+1',
        'standard_deviation':'configured population SD; assumption pending validation'}
    (REPORT/'innings1_build_summary.json').write_text(json.dumps(summary,indent=2)+'\n')
    print(json.dumps(summary,indent=2))

if __name__=='__main__':build()
